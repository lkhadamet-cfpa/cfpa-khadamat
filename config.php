<?php
declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| إعدادات منصة لجنة الخدمات الاجتماعية
|--------------------------------------------------------------------------
| مهم:
| لا تضع كلمة مرور قاعدة البيانات الحقيقية هنا.
| سيتم إعدادها لاحقًا في الاستضافة كمتغيرات بيئية.
|--------------------------------------------------------------------------
*/

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

/*
|--------------------------------------------------------------------------
| إعدادات التطبيق
|--------------------------------------------------------------------------
*/

define('APP_NAME', 'منصة لجنة الخدمات الاجتماعية');
define('APP_VERSION', '1.0.0');

/*
|--------------------------------------------------------------------------
| إعدادات قاعدة البيانات
|--------------------------------------------------------------------------
| حاليًا نتركها فارغة حتى لا نكشف أي معلومات سرية على GitHub.
| سنضع البيانات الحقيقية عند إعداد الخادم.
|--------------------------------------------------------------------------
*/

$dbHost = getenv('DB_HOST') ?: '';
$dbName = getenv('DB_NAME') ?: '';
$dbUser = getenv('DB_USER') ?: '';
$dbPass = getenv('DB_PASS') ?: '';

/*
|--------------------------------------------------------------------------
| الاتصال بقاعدة البيانات
|--------------------------------------------------------------------------
*/

$pdo = null;

if ($dbHost !== '' && $dbName !== '' && $dbUser !== '') {

    try {

        $dsn = "mysql:host={$dbHost};dbname={$dbName};charset=utf8mb4";

        $pdo = new PDO(
            $dsn,
            $dbUser,
            $dbPass,
            [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                PDO::ATTR_EMULATE_PREPARES => false
            ]
        );

    } catch (PDOException $e) {

        /*
        لا نعرض تفاصيل الخطأ للمستخدم
        حتى لا نكشف معلومات قاعدة البيانات.
        */

        error_log('Database connection error: ' . $e->getMessage());

        $pdo = null;
    }
}

/*
|--------------------------------------------------------------------------
| دالة التأكد من تسجيل الدخول
|--------------------------------------------------------------------------
*/

function isLoggedIn(): bool
{
    return isset($_SESSION['user_id']);
}

/*
|--------------------------------------------------------------------------
| الحصول على معرف المستخدم الحالي
|--------------------------------------------------------------------------
*/

function currentUserId(): ?int
{
    if (!isset($_SESSION['user_id'])) {
        return null;
    }

    return (int) $_SESSION['user_id'];
}

/*
|--------------------------------------------------------------------------
| حماية الصفحات التي تتطلب تسجيل الدخول
|--------------------------------------------------------------------------
*/

function requireLogin(): void
{
    if (!isLoggedIn()) {
        header('Location: /index.html');
        exit;
    }
}

/*
|--------------------------------------------------------------------------
| تسجيل الخروج
|--------------------------------------------------------------------------
*/

function logoutUser(): void
{
    $_SESSION = [];

    if (ini_get('session.use_cookies')) {

        $params = session_get_cookie_params();

        setcookie(
            session_name(),
            '',
            time() - 42000,
            $params['path'],
            $params['domain'],
            $params['secure'],
            $params['httponly']
        );
    }

    session_destroy();
}
